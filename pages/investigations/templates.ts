export const parseTemplateTokens = (text: string, c: InvestigationCase): string => {
    if (!text) return '';
    return text
        .replace(/{employee_name}/g, c.employeeName || 'غير محدد')
        .replace(/{employee_id}/g, c.employeeId || 'غير محدد')
        .replace(/{job_title}/g, c.employeeJobTitle || 'غير محدد')
        .replace(/{department}/g, c.employeeDepartment || 'غير محدد')
        .replace(/{case_number}/g, c.caseNumber || 'غير محدد')
        .replace(/{start_date}/g, c.startDate || 'غير محدد')
        .replace(/{investigator}/g, c.investigator || 'غير محدد')
        .replace(/{complainant_name}/g, c.complainantName || 'غير محدد')
        .replace(/{proposed_penalty}/g, c.proposedPenalty || 'تنبيه خطي بسيط مع لفت نظر مشدد لدرء التكرار');
};
